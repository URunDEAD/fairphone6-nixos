/* the measured 10-bit pedestal of all three sensors (tuning files) */
#define FP6_RAW_BLACK_10BIT 64

typedef struct
{
  Fp6LibcameraSrc *src;         /* ref */
  Fp6DngInfo info;
  guint8 *data;
  gchar *path;
  gchar *unique_model;
} Fp6DngJob;

/* raw fakesink pad (streaming thread of the raw pad) */
static GstPadProbeReturn
fp6r_probe (GstPad * pad, GstPadProbeInfo * pi, gpointer user)
{
  Fp6LibcameraSrc *self = user;
  Fp6Phase2 *p = self->p2;
  GstBuffer *buf = GST_PAD_PROBE_INFO_BUFFER (pi);
  Fp6DngJob *job;
  GstMapInfo map;
  GstElement *cam;
  gsize need;
  gint64 exp;
  gdouble gain, gr, gb;
  GDateTime *now;
  gchar *dt;

  g_mutex_lock (&p->lock);
  if (G_UNLIKELY (!p->raw_format)) {
    GstCaps *caps = gst_pad_get_current_caps (pad);
    GstStructure *s = caps ? gst_caps_get_structure (caps, 0) : NULL;
    if (s && gst_structure_has_name (s, "video/x-bayer")) {
      p->raw_format = g_strdup (gst_structure_get_string (s, "format"));
      gst_structure_get_int (s, "width", &p->raw_w);
      gst_structure_get_int (s, "height", &p->raw_h);
      if (!gst_structure_get_int (s, "stride", &p->raw_stride))
        p->raw_stride = 0;
      GST_INFO_OBJECT (self, "raw stream %s %dx%d stride %d",
          GST_STR_NULL (p->raw_format), p->raw_w, p->raw_h, p->raw_stride);
    }
    if (caps)
      gst_caps_unref (caps);
  }
  if (p->raw_state != RAW_ARMED || !p->raw_format || p->raw_h <= 0) {
    g_mutex_unlock (&p->lock);
    return GST_PAD_PROBE_OK;
  }
  if (!gst_buffer_map (buf, &map, GST_MAP_READ)) {
    g_mutex_unlock (&p->lock);
    return GST_PAD_PROBE_OK;
  }

  job = g_new0 (Fp6DngJob, 1);
  job->info.width = p->raw_w;
  job->info.height = p->raw_h;
  job->info.bits = strstr (p->raw_format, "12") ? 12 :
      strstr (p->raw_format, "10p") ? 10 : 16;
  need = job->info.bits == 10 ? ((gsize) p->raw_w * 5 + 3) / 4 :
      job->info.bits == 12 ? ((gsize) p->raw_w * 3 + 1) / 2 :
      (gsize) p->raw_w * 2;
  job->info.stride = p->raw_stride > 0 ? p->raw_stride :
      (gint) (map.size / p->raw_h);
  if ((gsize) job->info.stride < need
      || map.size < (gsize) job->info.stride * (p->raw_h - 1) + need
      || !fp6_dng_cfa_from_name (p->raw_format, p->swap_rb, job->info.cfa)) {
    gst_buffer_unmap (buf, &map);
    g_free (job);
    p->raw_state = RAW_ERROR;
    g_free (p->raw_error);
    p->raw_error = g_strdup_printf ("unusable raw buffer (%s, %" G_GSIZE_FORMAT
        " bytes)", p->raw_format, map.size);
    GST_WARNING_OBJECT (self, "%s", p->raw_error);
    g_mutex_unlock (&p->lock);
    return GST_PAD_PROBE_OK;
  }
  job->data = g_try_malloc (map.size);
  if (!job->data) {
    gst_buffer_unmap (buf, &map);
    g_free (job);
    p->raw_state = RAW_ERROR;
    g_free (p->raw_error);
    p->raw_error = g_strdup ("out of memory");
    g_mutex_unlock (&p->lock);
    return GST_PAD_PROBE_OK;
  }
  memcpy (job->data, map.data, map.size);
  gst_buffer_unmap (buf, &map);
  job->info.data = job->data;

  /* what this frame was taken with (libcamera metadata) */
  g_mutex_lock (&self->manual->lock);
  cam = self->manual->cam ? gst_object_ref (self->manual->cam) : NULL;
  g_mutex_unlock (&self->manual->lock);
  exp = fp6m_get_int (cam, "exposure-time");
  gain = fp6m_get_float (cam, "analogue-gain");
  gr = fp6m_get_array (cam, "colour-gains", 0, 0);
  gb = fp6m_get_array (cam, "colour-gains", 1, 0);
  if (cam)
    gst_object_unref (cam);

  job->info.black = FP6_RAW_BLACK_10BIT << (job->info.bits == 12 ? 2 :
      job->info.bits == 16 ? 0 : 0);
  job->info.white = (1u << (job->info.bits == 16 ? 10 : job->info.bits)) - 1;
  if (p->swap_rb) {
    /* the IPA balanced the mislabelled order: its "R" gain was applied to
     * the real blue pixels */
    gdouble t = gr;
    gr = gb;
    gb = t;
  }
  job->info.neutral[0] = gr > 0 ? 1.0 / gr : 1.0;
  job->info.neutral[1] = 1.0;
  job->info.neutral[2] = gb > 0 ? 1.0 / gb : 1.0;
  memcpy (job->info.cm1, fp6_raw_colour[p->sensor].cm1, sizeof job->info.cm1);
  memcpy (job->info.cm2, fp6_raw_colour[p->sensor].cm2, sizeof job->info.cm2);
  job->info.illum1 = 17;
  job->info.illum2 = 21;
  job->info.orientation = fp6_dng_orientation (p->flip, p->raw_rotate);
  job->info.make = "Fairphone";
  job->info.model = "FP6";
  job->unique_model = g_strdup_printf ("Fairphone FP6 %s",
      fp6_sensor_names[p->sensor]);
  job->info.unique_model = job->unique_model;
  job->info.software = "lomiri-camera-app (fp6 raw)";
  job->info.exposure_s = exp > 0 ? exp / 1e6 : 0;
  job->info.iso = gain > 0 ? (gint) lround (gain * 100) : 0;
  now = g_date_time_new_now_local ();
  dt = g_date_time_format (now, "%Y:%m:%d %H:%M:%S");
  g_strlcpy (job->info.datetime, dt ? dt : "", sizeof job->info.datetime);
  g_free (dt);
  g_date_time_unref (now);
  job->path = g_strdup (p->raw_path);
  job->src = gst_object_ref (self);
  p->raw_state = RAW_SAVING;
  GST_INFO_OBJECT (self, "raw frame grabbed (%s, exposure %" G_GINT64_FORMAT
      " us, gain %.2f, gains %.3f/%.3f, orientation %u) -> %s",
      p->raw_format, exp, gain, gr, gb, job->info.orientation, job->path);
  g_mutex_unlock (&p->lock);

  g_thread_unref (g_thread_new ("fp6-dng", fp6p2_dng_thread, job));
  return GST_PAD_PROBE_OK;
}

static gpointer
fp6p2_dng_thread (gpointer data)
{
  Fp6DngJob *job = data;
  Fp6Phase2 *p = job->src->p2;
  GError *err = NULL;
  gchar *dir = g_path_get_dirname (job->path);
  gboolean ok;

  g_mkdir_with_parents (dir, 0755);
  g_free (dir);
  ok = fp6_dng_write (job->path, &job->info, &err);

  g_mutex_lock (&p->lock);
  if (ok) {
    g_free (p->raw_result);
    p->raw_result = g_strdup (job->path);
    p->raw_state = RAW_DONE;
    GST_INFO_OBJECT (job->src, "DNG saved: %s", job->path);
  } else {
    g_free (p->raw_error);
    p->raw_error = g_strdup (err ? err->message : "DNG write failed");
    p->raw_state = RAW_ERROR;
    GST_WARNING_OBJECT (job->src, "DNG failed: %s", p->raw_error);
  }
  g_mutex_unlock (&p->lock);
  g_clear_error (&err);
  g_free (job->data);
  g_free (job->path);
  g_free (job->unique_model);
  gst_object_unref (job->src);
  g_free (job);
  return NULL;
}

/* "raw-capture": DNG of the next raw frame. rotate: clockwise display
 * rotation, as passed to stack-start. */
static gboolean
fp6r_capture (Fp6LibcameraSrc * self, const gchar * path, gint rotate,
    gpointer unused)
{
  Fp6Phase2 *p = self->p2;
  gboolean ok;

  g_mutex_lock (&p->lock);
  ok = path && *path && p->raw_built && p->raw_format
      && p->raw_state != RAW_SAVING;
  if (ok) {
    g_free (p->raw_path);
    p->raw_path = g_strdup (path);
    p->raw_rotate = rotate;
    p->raw_armed_at = g_get_monotonic_time ();
    g_clear_pointer (&p->raw_error, g_free);
    p->raw_state = RAW_ARMED;
  }
  g_mutex_unlock (&p->lock);
  GST_INFO_OBJECT (self, "raw capture %s: %s", ok ? "armed" : "refused",
      GST_STR_NULL (path));
  return ok;
}

/* lsrc_build: request the raw pad and terminate it in the bin */
static void
fp6r_build (Fp6LibcameraSrc * self, GstElement * cam)
{
  Fp6Phase2 *p = self->p2;
  GstPadTemplate *tpl;
  GstPad *rp = NULL, *sp;
  GstElement *filter, *sink;
  GstCaps *caps;

  tpl = gst_element_class_get_pad_template (GST_ELEMENT_GET_CLASS (cam),
      "src_%u");
  if (tpl)
    rp = gst_element_request_pad (cam, tpl, NULL, NULL);
  filter = gst_element_factory_make ("capsfilter", "fp6-raw-caps");
  sink = gst_element_factory_make ("fakesink", "fp6-raw-sink");
  if (!rp || !filter || !sink) {
    GST_WARNING_OBJECT (self, "raw stream unavailable (no request pad)");
    if (rp)
      gst_element_release_request_pad (cam, rp);
    g_clear_object (&filter);
    g_clear_object (&sink);
    g_clear_object (&rp);
    return;
  }
  gst_util_set_object_arg (G_OBJECT (rp), "stream-role", "raw");
  caps = gst_caps_new_empty_simple ("video/x-bayer");
  g_object_set (filter, "caps", caps, NULL);
  gst_caps_unref (caps);
  g_object_set (sink, "sync", FALSE, "async", FALSE, "enable-last-sample",
      FALSE, "qos", FALSE, NULL);
  /* not a sink of the pipeline: camerabin must see a plain source bin
   * (EOS/preroll/latency accounting) */
  GST_OBJECT_FLAG_UNSET (sink, GST_ELEMENT_FLAG_SINK);
  gst_bin_add_many (GST_BIN (self), filter, sink, NULL);
  sp = gst_element_get_static_pad (filter, "sink");
  if (gst_pad_link (rp, sp) != GST_PAD_LINK_OK
      || !gst_element_link (filter, sink)) {
    GST_WARNING_OBJECT (self, "cannot link the raw stream");
    gst_object_unref (sp);
    gst_bin_remove_many (GST_BIN (self), filter, sink, NULL);
    gst_element_release_request_pad (cam, rp);
    gst_object_unref (rp);
    return;
  }
  gst_object_unref (sp);
  sp = gst_element_get_static_pad (sink, "sink");
  gst_pad_add_probe (sp, GST_PAD_PROBE_TYPE_BUFFER, fp6r_probe, self, NULL);
  gst_object_unref (sp);
  gst_object_unref (rp);
  g_mutex_lock (&p->lock);
  p->raw_built = TRUE;
  g_mutex_unlock (&p->lock);
  GST_INFO_OBJECT (self, "raw stream requested");
}
